"""
Логирование модуля auth.

Что делает этот файл: задаёт УРОВЕНЬ логирования для логгера "auth".

Чего НЕ делает (важно!):
- не создаёт файлы журнала;
- не настраивает root-логгер;
- не «отрезает» логи от общего журнала (propagate остаётся True).

Почему так: куда писать логи (файл, консоль) — решает ПРИЛОЖЕНИЕ
(в main.py через logging.basicConfig). Модуль лишь управляет своим
уровнем (сколько деталей показывать: DEBUG / INFO / ...).

Благодаря этому логи всех модулей попадают в ОДИН общий журнал
приложения, и видна вся цепочка событий в хронологическом порядке.
"""

import logging

def setup_logging(level: str = "INFO"):
    """
    Задаёт уровень логирования для логгера "auth".
    Вызывается в AuthModule.init_app().

    Args:
        level: "DEBUG" | "INFO" | "WARNING" | "ERROR"
        (берётся из settings.LOG_LEVEL)
    """

    logger = logging.getLogger("auth")                                          # Получаем (или создаём) логгер с именем "auth"
    logger.setLevel(getattr(logging, level.upper(), logging.INFO))              # Задаём уровень логирования, по умолчанию INFO
