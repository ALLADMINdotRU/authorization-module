"""
«Мост» для передачи зависимостей от корневого проекта в модуль.

Проблема: модуль auth — переносимый. Он не знает, как в чужом
проекте называется файл с настройками БД и где лежит функция get_db.

Решение: корень при инициализации КЛАДЁТ сюда свою get_db,
а роутеры модуля берут её отсюда. Это паттерн «внедрение зависимостей».
"""

# Сюда корень положит свою зависимость get_db (пока пусто)
_get_db = None

def set_get_db(get_db_func):
    """
    Корень вызывает эту функцию в init_app(), чтобы передать
    свою зависимость сессии БД.

    Args:
        get_db_func: асинхронная функция-зависимость из корневого database.py
    """
    global _get_db
    _get_db = get_db_func


async  def get_db():
    """
    Возвращает корневую get_db (для использования в Depends).

    Так как корневая get_db — это АСИНХРОННЫЙ генератор (async def + yield),
    мы должны «передать» его через async for, а не yield from.
    """
    if _get_db is None:
        raise RuntimeError(
            "Модуль auth не инициализирован. "
            "Вызови auth_module.init_app(...) до использования роутов."
        )
    # async for — перебираем асинхронный генератор корня
    # и отдаём каждую сессию дальше
    async for db in _get_db():
        yield db